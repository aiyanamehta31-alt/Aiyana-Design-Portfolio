// Embeds Wiglet's original scheduler.py and the JavaScript port as strings in
// js/wiglet/scheduler-source.js, so the "View the real scheduler" tab works as
// a classic script (no fetch), even from file://.
//
//   node tools/embed-wiglet-source.mjs <path to the Wiglet repo>
//
// Only these two files are read. The Wiglet repo's secrets (.env,
// credentials.json, token.json) are never opened.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const repo = process.argv[2];
if (!repo) { console.error('usage: node tools/embed-wiglet-source.mjs <wiglet repo>'); process.exit(1); }

const python = readFileSync(join(repo, 'wiglet', 'scheduler.py'), 'utf8');
const js = readFileSync(new URL('../js/wiglet/scheduler.js', import.meta.url), 'utf8');

// Refuse anything key-shaped, just in case.
const KEYISH = /(gsk_|sk-ant-|\bsk-[A-Za-z0-9]{8,}|AIza[0-9A-Za-z_-]{10,}|client_secret|refresh_token)/;
for (const [name, text] of [['scheduler.py', python], ['scheduler.js', js]]) {
  if (KEYISH.test(text)) { console.error('Refusing: ' + name + ' contains a key-shaped string.'); process.exit(1); }
}

const out = '/* Generated by tools/embed-wiglet-source.mjs. Do not edit by hand.\n' +
  '   The original wiglet/scheduler.py and its JavaScript port, as strings. */\n' +
  'window.WigletSources = ' + JSON.stringify({ python, js }, null, 0) + ';\n';
writeFileSync(new URL('../js/wiglet/scheduler-source.js', import.meta.url), out);
console.log('wrote js/wiglet/scheduler-source.js', out.length, 'bytes');
